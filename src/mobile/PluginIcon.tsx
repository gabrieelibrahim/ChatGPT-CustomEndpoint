/** The bundled logo file for a catalog plugin, if one is verified. */
export const pluginMark = (id: string) => marks[id] ? '/plugin-icons/' + marks[id] : undefined;
export function PluginIcon({ id, name, icon }: { id: string; name: string; icon?: string }) {
  const symbol = icon || id;
  let content;
  if (marks[id]) content = <img src={'/plugin-icons/' + marks[id]} alt="" loading="lazy" draggable={false}/>;
  else if (['globe', 'spaces', 'book', 'shield', 'mail', 'comment'].includes(symbol)) content = <UIIcon name={symbol}/>;
  else if (symbol === 'templates') content = <svg viewBox="0 0 32 32" fill="none"><rect x="2" y="2" width="12" height="28" rx="4" fill="#25c7f3"/><path d="m9 20 10-15a5 5 0 0 1 7 0l4 4a5 5 0 0 1 0 7L16 30H9Z" fill="#f56b88"/><path d="M17 21h11a3 3 0 0 1 3 3v6H15Z" fill="#fbd22e"/></svg>;
  else if (symbol === 'management') content = <span className="m-plugin-flower">✣</span>;
  else content = <span className="m-plugin-monogram">{name.slice(0, 2).trim()}</span>;
  return <span className={'m-plugin-icon m-plugin-icon-' + symbol + (marks[id] ? ' m-plugin-mark' : '')} data-plugin-icon={id} aria-hidden="true">{content}</span>;
}
